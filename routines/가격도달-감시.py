"""가격 도달 감시 — 시각이 아니라 **사건**으로 깨어나는 루틴.

카테고리: 정보수집 (읽기만 합니다. 주문이 나가지 않습니다)

다른 루틴과 무엇이 다른가:
  아침 브리핑은 「매일 8시」에 옵니다. 시각이 정해져 있습니다.
  가격 도달은 시각을 모릅니다. 오늘 올 수도, 한 달 뒤에 올 수도 있습니다.
  그래서 이 파일은 **지금 상태 한 줄만** 찍고 끝냅니다. 알림은 보내지 않습니다.

  hermes 가 이 출력을 10분마다 읽고 **직전과 같으면 아무것도 하지 않습니다.**
  달라졌을 때만 깨웁니다. 그래서 같은 알림이 반복해서 오지 않습니다.

  crontab 으로 같은 걸 하려면 「직전 값」을 파일에 저장하고 비교하는 코드를
  직접 짜야 합니다. hermes 는 그 비교를 대신해 줍니다. 그게 이 층을 두는 이유입니다.

⚠️ 출력에 시각을 넣지 마세요. 매번 달라져서 늘 깨어납니다.

혼자 돌려 보기:  python routines/가격도달-감시.py
"""
import sys

from _routine import ROOT

sys.path.insert(0, str(ROOT / "src"))
sys.path.insert(0, str(ROOT / "agent"))

from common import market  # noqa: E402

# ────────────────────────────────────────────────────────────
# 지시사항 — 무엇을 얼마에 지켜볼 것인가
# ────────────────────────────────────────────────────────────
관심 = [
    {"이름": "삼성전자", "코드": "005930", "아래로": 250_000, "위로": 300_000},
    {"이름": "현대차", "코드": "005380", "아래로": 380_000, "위로": 450_000},
    {"이름": "코스피", "코드": "^KS11", "아래로": 6_500, "위로": 7_200},
]
# ────────────────────────────────────────────────────────────


def 상태(값: float, 아래로: float, 위로: float) -> str:
    """세 가지 중 하나. 이 문자열이 바뀔 때만 hermes 가 깨어난다."""
    if 값 <= 아래로:
        return "아래로 내려옴"
    if 값 >= 위로:
        return "위로 올라감"
    return "사이"


def main() -> None:
    줄 = []
    for w in 관심:
        try:
            값 = market.last(market.to_symbol(w["코드"]))
        except market.MarketError:
            줄.append(f"{w['이름']} 조회실패")   # 값이 아니라 상태다. 계속 실패해도 한 번만 깨운다
            continue
        줄.append(f"{w['이름']} {상태(값, w['아래로'], w['위로'])}")
    # 시각도, 소수점도 넣지 않는다. 상태가 같으면 글자도 같아야 한다.
    print(" · ".join(줄))


if __name__ == "__main__":
    main()
